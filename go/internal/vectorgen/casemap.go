package main

import (
	"bytes"
	"fmt"
	"unicode"
)

const (
	caseMapCommand   = "go -C go run ./internal/vectorgen casemap > spec/case_mapping.json"
	caseSwiftCommand = "go -C go run ./internal/vectorgen caseswift > swift/Sources/TesseraCore/CaseTables.swift"
)

type casePair struct{ from, to rune }

type caseRun struct {
	lo, hi, stride rune
	delta          rune
}

func isScalar(r rune) bool { return r < 0xD800 || (r > 0xDFFF && r <= unicode.MaxRune) }

func casePairs(f func(rune) rune) []casePair {
	var out []casePair
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if !isScalar(r) {
			continue
		}
		if m := f(r); m != r {
			out = append(out, casePair{r, m})
		}
	}
	return out
}

func caseRuns(pairs []casePair) []caseRun {
	var runs []caseRun
	for _, p := range pairs {
		d := p.to - p.from
		if n := len(runs); n > 0 {
			last := &runs[n-1]
			gap := p.from - last.hi
			if d == last.delta && ((last.stride == 0 && (gap == 1 || gap == 2)) || (last.stride != 0 && gap == last.stride)) {
				last.stride, last.hi = gap, p.from
				continue
			}
		}
		runs = append(runs, caseRun{lo: p.from, hi: p.from, delta: d})
	}
	for i := range runs {
		if runs[i].stride == 0 {
			runs[i].stride = 1
		}
	}
	return runs
}

func caseMappingJSON() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "{\n  \"_about\": \"Go unicode.ToLower and unicode.ToUpper (the simple per-scalar mappings) for every scalar they change, as [from, to]; every other scalar maps to itself. Regenerate: %s\",\n", caseMapCommand)
	fmt.Fprintf(&b, "  \"unicode_version\": %q,\n", unicode.Version)
	for i, m := range []struct {
		key string
		f   func(rune) rune
	}{{"lower", unicode.ToLower}, {"upper", unicode.ToUpper}} {
		fmt.Fprintf(&b, "  %q: [\n", m.key)
		pairs := casePairs(m.f)
		for j, p := range pairs {
			sep := ","
			if j == len(pairs)-1 {
				sep = ""
			}
			fmt.Fprintf(&b, "    [%d, %d]%s\n", p.from, p.to, sep)
		}
		if i == 0 {
			b.WriteString("  ],\n")
		} else {
			b.WriteString("  ]\n")
		}
	}
	b.WriteString("}\n")
	return b.Bytes()
}

func caseSwift() []byte {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Generated by `%s`. Do not edit.\n\n", caseSwiftCommand)
	b.WriteString("enum CaseTables {\n")
	fmt.Fprintf(&b, "    static let unicodeVersion = %q\n", unicode.Version)
	for _, m := range []struct {
		key string
		f   func(rune) rune
	}{{"lower", unicode.ToLower}, {"upper", unicode.ToUpper}} {
		fmt.Fprintf(&b, "\n    static let %s: [Int32] = [\n", m.key)
		for _, r := range caseRuns(casePairs(m.f)) {
			fmt.Fprintf(&b, "        0x%04X, 0x%04X, %d, %d,\n", r.lo, r.hi, r.stride, r.delta)
		}
		b.WriteString("    ]\n")
	}
	b.WriteString("}\n")
	return b.Bytes()
}
