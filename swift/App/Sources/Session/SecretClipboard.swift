import AppKit

@MainActor
final class SecretClipboard {
    enum Kind: Sendable { case code, secret }

    var pendingClear: Task<Void, Never>?
    private var lastCopy: (name: NSPasteboard.Name, changeCount: Int)?

    /// The one place anything reaches the pasteboard. Every copy declares the
    /// nspasteboard.com hints so clipboard managers neither store nor sync a
    /// secret, and expires after `pasteboardExpiry` — guarded by `changeCount`,
    /// so a copy the user made in the meantime is never wiped. A rotating code
    /// is additionally marked transient (it is worthless once its period ends).
    func copy(_ value: String, kind: Kind, to pasteboard: NSPasteboard = .general) {
        let pb = pasteboard
        pb.clearContents()
        pb.setString(value, forType: .string)
        pb.setString("", forType: .nsConcealed)
        pb.setString("", forType: .nsAutoGenerated)
        if kind == .code { pb.setString("", forType: .nsTransient) }

        let stamp = pb.changeCount
        let name = pb.name
        lastCopy = (name, stamp)
        pendingClear?.cancel()
        pendingClear = Task { @MainActor in
            try? await Task.sleep(for: .seconds(AppModel.pasteboardExpiry))
            guard !Task.isCancelled else { return }
            let pb = NSPasteboard(name: name)
            guard pb.changeCount == stamp else { return }   // the user copied something else
            pb.clearContents()
        }
    }

    func clearIfOwned() {
        pendingClear?.cancel()
        pendingClear = nil
        guard let last = lastCopy else { return }
        lastCopy = nil
        let pb = NSPasteboard(name: last.name)
        guard pb.changeCount == last.changeCount else { return }
        pb.clearContents()
    }
}
