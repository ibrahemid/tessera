import AppKit

@MainActor
final class SecretClipboard {
    enum Kind: Sendable { case code, secret }

    typealias Scheduler = @MainActor (_ delay: Duration, _ action: @escaping @MainActor () -> Void) -> Task<Void, Never>

    static let sleepThenRun: Scheduler = { delay, action in
        Task { @MainActor in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled else { return }
            action()
        }
    }

    private(set) var pendingClear: Task<Void, Never>?
    private let pasteboard: any SecretPasteboard
    private let expiry: Duration
    private let schedule: Scheduler
    private let observers = NotificationObservers()
    private var owned: (pasteboard: any SecretPasteboard, changeCount: Int)?

    init(pasteboard: any SecretPasteboard = NSPasteboard.general,
         expiry: Duration = .seconds(AppModel.pasteboardExpiry),
         center: NotificationCenter = .default,
         schedule: @escaping Scheduler = SecretClipboard.sleepThenRun) {
        self.pasteboard = pasteboard
        self.expiry = expiry
        self.schedule = schedule
        observers.add(center, center.addObserver(forName: .tesseraVaultDidLock, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.clearIfOwned() }
        })
    }

    @discardableResult
    func copy(_ value: String, kind: Kind) -> Bool {
        copy(value, kind: kind, to: pasteboard)
    }

    @discardableResult
    func copy(_ value: String, kind: Kind, to target: any SecretPasteboard) -> Bool {
        pendingClear?.cancel()
        pendingClear = nil
        owned = nil
        guard let item = Self.item(value, kind: kind) else { return false }
        _ = target.prepareForNewContents(with: .currentHostOnly)
        guard target.writeObjects([item]) else { return false }
        owned = (target, target.changeCount)
        pendingClear = schedule(expiry) { [weak self] in self?.clearIfOwned() }
        return true
    }

    func clearIfOwned() {
        pendingClear?.cancel()
        pendingClear = nil
        guard let owned else { return }
        self.owned = nil
        guard owned.pasteboard.changeCount == owned.changeCount else { return }
        owned.pasteboard.clearContents()
    }

    static func types(for kind: Kind) -> [NSPasteboard.PasteboardType] {
        let markers: [NSPasteboard.PasteboardType] = [.nsConcealed, .nsTransient]
        return [.string] + markers + (kind == .code ? [.nsAutoGenerated] : [])
    }

    private static func item(_ value: String, kind: Kind) -> NSPasteboardItem? {
        let item = NSPasteboardItem()
        for type in types(for: kind) {
            guard item.setString(type == .string ? value : "", forType: type) else { return nil }
        }
        return item
    }
}
