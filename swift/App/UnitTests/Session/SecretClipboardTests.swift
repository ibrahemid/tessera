import AppKit
import XCTest
@testable import Tessera

@MainActor
private final class FakePasteboard: SecretPasteboard {
    private(set) var changeCount = 0
    private(set) var preparedOptions: [NSPasteboard.ContentsOptions] = []
    private(set) var writes: [[any NSPasteboardWriting]] = []
    private(set) var clears = 0
    var refusesWrites = false

    func prepareForNewContents(with options: NSPasteboard.ContentsOptions) -> Int {
        preparedOptions.append(options)
        changeCount += 1
        return changeCount
    }

    func writeObjects(_ objects: [any NSPasteboardWriting]) -> Bool {
        guard !refusesWrites else { return false }
        writes.append(objects)
        changeCount += 1
        return true
    }

    func clearContents() -> Int {
        clears += 1
        changeCount += 1
        return changeCount
    }

    func userCopiesSomethingElse() { changeCount += 1 }
}

@MainActor
private final class ManualScheduler {
    private(set) var delays: [Duration] = []
    private var latest: (@MainActor () -> Void)?

    var schedule: SecretClipboard.Scheduler {
        { [self] delay, action in
            delays.append(delay)
            latest = action
            return Task {}
        }
    }

    func fire() { latest?() }
}

@MainActor
final class SecretClipboardTests: XCTestCase {
    private let center = NotificationCenter()

    private func makeClipboard(_ pasteboard: any SecretPasteboard, _ scheduler: ManualScheduler) -> SecretClipboard {
        SecretClipboard(pasteboard: pasteboard, center: center, schedule: scheduler.schedule)
    }

    private func postLock(_ reason: LockReason) {
        center.post(name: .tesseraVaultDidLock, object: nil, userInfo: ["reason": reason.rawValue])
    }

    private func makeRealPasteboard() -> NSPasteboard {
        let pasteboard = NSPasteboard(name: NSPasteboard.Name("tessera.tests.\(UUID().uuidString)"))
        addTeardownBlock { @MainActor in pasteboard.releaseGlobally() }
        return pasteboard
    }

    private func types(of object: any NSPasteboardWriting) -> Set<NSPasteboard.PasteboardType> {
        Set((object as? NSPasteboardItem)?.types ?? [])
    }

    func testCopyRestrictsThePasteboardToThisMac() {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        XCTAssertTrue(clipboard.copy("123456", kind: .code))
        XCTAssertEqual(pasteboard.preparedOptions, [.currentHostOnly])
    }

    func testCodeIsOneItemWithTheStringAndAllThreeMarkers() throws {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        clipboard.copy("123456", kind: .code)
        XCTAssertEqual(pasteboard.writes.count, 1)
        XCTAssertEqual(pasteboard.writes.first?.count, 1)
        let item = try XCTUnwrap(pasteboard.writes.first?.first as? NSPasteboardItem)
        XCTAssertEqual(Set(item.types), [.string, .nsConcealed, .nsTransient, .nsAutoGenerated])
        XCTAssertEqual(item.string(forType: .string), "123456")
    }

    func testSecretIsOneItemMarkedConcealedAndTransient() throws {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        clipboard.copy("JBSWY3DPEHPK3PXP", kind: .secret)
        XCTAssertEqual(pasteboard.writes.count, 1)
        let object = try XCTUnwrap(pasteboard.writes.first?.first)
        XCTAssertEqual(types(of: object), [.string, .nsConcealed, .nsTransient])
    }

    func testCopyExpiresAfterThePasteboardExpiry() {
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(FakePasteboard(), scheduler)
        clipboard.copy("123456", kind: .code)
        XCTAssertEqual(scheduler.delays, [.seconds(AppModel.pasteboardExpiry)])
    }

    func testTimerClearsTheCopyItMade() {
        let pasteboard = FakePasteboard()
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        clipboard.copy("123456", kind: .code)
        scheduler.fire()
        XCTAssertEqual(pasteboard.clears, 1)
    }

    func testTimerLeavesWhatTheUserCopiedSince() {
        let pasteboard = FakePasteboard()
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        clipboard.copy("123456", kind: .code)
        pasteboard.userCopiesSomethingElse()
        scheduler.fire()
        XCTAssertEqual(pasteboard.clears, 0)
    }

    func testLockNotificationClearsTheCopyItMade() {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        clipboard.copy("123456", kind: .code)
        postLock(.screenLocked)
        XCTAssertEqual(pasteboard.clears, 1)
        XCTAssertNil(clipboard.pendingClear)
    }

    func testQuitClearsTheCopyItMade() {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        clipboard.copy("JBSWY3DPEHPK3PXP", kind: .secret)
        postLock(.quit)
        XCTAssertEqual(pasteboard.clears, 1)
    }

    func testLockNotificationLeavesWhatTheUserCopiedSince() {
        let pasteboard = FakePasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        clipboard.copy("123456", kind: .code)
        pasteboard.userCopiesSomethingElse()
        postLock(.manual)
        XCTAssertEqual(pasteboard.clears, 0)
    }

    func testClearHappensOncePerCopy() {
        let pasteboard = FakePasteboard()
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        clipboard.copy("123456", kind: .code)
        postLock(.sleep)
        scheduler.fire()
        postLock(.quit)
        XCTAssertEqual(pasteboard.clears, 1)
    }

    func testRefusedWriteReportsFailureAndOwnsNothing() {
        let pasteboard = FakePasteboard()
        pasteboard.refusesWrites = true
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        XCTAssertFalse(clipboard.copy("123456", kind: .code))
        XCTAssertTrue(scheduler.delays.isEmpty)
        XCTAssertNil(clipboard.pendingClear)
        postLock(.manual)
        XCTAssertEqual(pasteboard.clears, 0)
    }

    func testRealPasteboardHoldsOneItemWithTheExactTypes() throws {
        let pasteboard = makeRealPasteboard()
        let clipboard = makeClipboard(pasteboard, ManualScheduler())
        XCTAssertTrue(clipboard.copy("123456", kind: .code))
        let items = try XCTUnwrap(pasteboard.pasteboardItems)
        XCTAssertEqual(items.count, 1)
        XCTAssertEqual(Set(items[0].types), [.string, .nsConcealed, .nsTransient, .nsAutoGenerated])
        XCTAssertEqual(pasteboard.string(forType: .string), "123456")
    }

    func testRealPasteboardClearsOnLockAndOnTimer() {
        let pasteboard = makeRealPasteboard()
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        clipboard.copy("123456", kind: .code)
        postLock(.idle)
        XCTAssertNil(pasteboard.string(forType: .string))
        clipboard.copy("654321", kind: .code)
        scheduler.fire()
        XCTAssertNil(pasteboard.string(forType: .string))
    }

    func testRealPasteboardKeepsWhatTheUserCopiedSince() {
        let pasteboard = makeRealPasteboard()
        let scheduler = ManualScheduler()
        let clipboard = makeClipboard(pasteboard, scheduler)
        clipboard.copy("123456", kind: .code)
        pasteboard.clearContents()
        pasteboard.setString("keep", forType: .string)
        postLock(.manual)
        scheduler.fire()
        XCTAssertEqual(pasteboard.string(forType: .string), "keep")
    }

    func testSetupKeyCopyFailureSaysSo() throws {
        let model = AppModel(demo: .populated)
        let pasteboard = FakePasteboard()
        pasteboard.refusesWrites = true
        let account = try XCTUnwrap(model.accounts.first)
        model.copySecretKey(account, to: pasteboard)
        XCTAssertEqual(model.notice, .failure(UserMessage.copyFailed))
        model.copySetupLink(account, to: pasteboard)
        XCTAssertEqual(model.notice, .failure(UserMessage.copyFailed))
    }

    func testSetupKeyCopyIsASecretWithoutTheAutoGeneratedMarker() throws {
        let model = AppModel(demo: .populated)
        defer { model.clipboard.pendingClear?.cancel() }
        let pasteboard = FakePasteboard()
        let account = try XCTUnwrap(model.accounts.first)
        model.copySecretKey(account, to: pasteboard)
        XCTAssertEqual(model.notice, .info("Copied setup key for \(account.displayName)"))
        let object = try XCTUnwrap(pasteboard.writes.first?.first)
        XCTAssertEqual(types(of: object), [.string, .nsConcealed, .nsTransient])
    }
}
